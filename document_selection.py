def normalize_document_titles(values: Any) -> list[str]:
    if not isinstance(values, list):
        return []
    result = []
    for value in values:
        title = normalize_document_title(value)
        if title in DOCUMENT_CATEGORY_BY_TITLE and title not in result:
            result.append(title)
    return result


