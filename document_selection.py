def sanitize_risk_facts(raw_facts: Any) -> list[dict[str, Any]]:
    if isinstance(raw_facts, dict):
        raw_facts = raw_facts.get("risk_facts") or raw_facts.get("facts") or []
    if not isinstance(raw_facts, list):
        return []

    facts = []
    for item in raw_facts:
        if not isinstance(item, dict):
            continue
        risk_type = str(item.get("risk_type") or item.get("risk") or "").strip()
        evidence = str(item.get("evidence") or item.get("原文证据") or "").strip()
        if not risk_type or not evidence:
            continue

        related_documents = normalize_document_titles(
            item.get("related_documents")
            or item.get("documents")
            or item.get("文书")
            or []
        )
        if not related_documents:
            continue

        facts.append(
            {
                "risk_type": risk_type,
                "evidence": evidence[:500],
                "related_documents": related_documents,
            }
        )
    return facts


def build_pre_meeting_document_counts(pre_meeting: dict | None) -> dict[str, int]:
    if not isinstance(pre_meeting, dict):
        return DocumentCounts()

    counts = DocumentCounts()
    for group_key, values in pre_meeting.items():
        fallback_category = PRE_MEETING_GROUP_CATEGORY.get(group_key)
        if not isinstance(values, list):
            continue
        for value in values:
            if isinstance(value, dict):
                value = (
                    value.get("templateName")
                    or value.get("TemplateName")
                    or value.get("documentName")
                    or value.get("DocumentName")
                    or value.get("name")
                    or value.get("Name")
                    or ""
                )
            title = normalize_document_title(value)
            if title:
                counts.add(title, 1, document_category_for_title(title) or fallback_category)

    return counts


def extract_standard_documents_from_text(text: str) -> set[str]:
    if not text:
        return set()
    normalized_text = str(text).replace("(", "（").replace(")", "）")
    documents: set[str] = set()
    for title in DOCUMENT_CATEGORY_BY_TITLE:
        if title in normalized_text or f"《{title}》" in normalized_text:
            documents.add(title)
    return documents


def build_meeting_document_counts(*texts: str) -> dict[str, int]:
    counts = DocumentCounts()
    for title in extract_standard_documents_from_text("\n".join(str(text or "") for text in texts)):
        counts.add(title, 1, document_category_for_title(title))
    return counts


def build_risk_fact_document_counts(risk_facts: Any) -> dict[str, int]:
    counts = DocumentCounts()
    for fact in sanitize_risk_facts(risk_facts):
        for title in fact.get("related_documents", []):
            counts.add(title, 1, document_category_for_title(title))
    return counts


