def format_risk_facts_for_prompt(risk_facts: Any) -> str:
    facts = sanitize_risk_facts(risk_facts)
    if not facts:
        return ""

    lines = []
    for index, fact in enumerate(facts, start=1):
        documents = "、".join(f"《{title}》" for title in fact["related_documents"])
        lines.append(
            f"{index}. 风险类型：{fact['risk_type']}\n"
            f"   原文证据：{fact['evidence']}\n"
            f"   对应文书：{documents}"
        )
    return "\n".join(lines)
