class DocumentCounts(dict):
    """Document count mapping with per-title category metadata."""

    def __init__(self, *args, categories: dict[str, str] | None = None, **kwargs):
        super().__init__(*args, **kwargs)
        self.categories: dict[str, str] = dict(categories or {})

    def add(self, title: str, count: int = 1, category: str | None = None) -> None:
        if not title:
            return
        normalized = normalize_document_title(title)
        self[normalized] = int(self.get(normalized, 0) or 0) + max(int(count or 1), 1)
        resolved_category = category or document_category_for_title(normalized)
        if resolved_category:
            self.categories[normalized] = resolved_category

    def merge(self, other: dict[str, int]) -> None:
        other_categories = getattr(other, "categories", {})
        for title, count in other.items():
            self.add(title, count, other_categories.get(title) or other_categories.get(normalize_document_title(title)))


def normalize_document_title(value: Any) -> str:
    text = str(value or "").strip()
    match = re.search(r"《([^》]+)》", text)
    if match:
        text = match.group(1)
    text = text.strip("《》").replace("(", "（").replace(")", "）")
    key = re.sub(r"\s+", "", text)
    return DOCUMENT_TITLE_ALIASES.get(key, text)


def document_category_for_title(title: str, categories: dict[str, str] | None = None) -> str | None:
    normalized = normalize_document_title(title)
    if categories and normalized in categories:
        return categories[normalized]
    if normalized in DOCUMENT_CATEGORY_BY_TITLE:
        return DOCUMENT_CATEGORY_BY_TITLE[normalized]
    if any(keyword in normalized for keyword in ("劳动合同", "劳务", "超龄人员", "实习", "派遣", "计件工", "计时工", "非全日制", "试用期", "续签")):
        return "一、用工模式与劳动合同签署"
    if any(keyword in normalized for keyword in ("社保", "社会保险", "公积金", "工伤", "工资条", "复岗")):
        return "二、社保、公积金及工伤合规"
    if any(keyword in normalized for keyword in ("规章", "制度", "员工手册", "奖惩", "宿舍", "安全管理")):
        return "三、规章制度合规"
    if any(keyword in normalized for keyword in ("考勤", "加班", "请假", "年假", "节假日", "休假")):
        return "四、工时、加班与休假合规"
    if any(keyword in normalized for keyword in ("面试", "入职", "背景调查", "背调", "无离职证明")):
        return "五、员工入职合规"
    if any(keyword in normalized for keyword in ("工资发放", "薪资", "发薪", "工资账号", "调薪")):
        return "六、薪资发放合规"
    if any(keyword in normalized for keyword in ("离职", "辞退", "返岗", "解除劳动", "交接")):
        return "七、员工离职合规"
    if any(keyword in normalized for keyword in ("保密", "竞业", "培训服务期", "专项协议")):
        return "八、专项协议合规"
    return None


def document_sort_key(title: str, categories: dict[str, str] | None = None) -> tuple[int, int, str]:
    category = document_category_for_title(title, categories)
    return (
        DOCUMENT_CATEGORY_ORDER.get(category or "", 999),
        DOCUMENT_ORDER.get(normalize_document_title(title), 9999),
        normalize_document_title(title),
    )


